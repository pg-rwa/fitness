function seed() {
  const insertProperty = db.prepare(`
    INSERT OR REPLACE INTO properties (id, name, description, property_type, city, country, latitude, longitude, price_per_night, max_guests, bedrooms, bathrooms, rating, review_count, host_name)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
  `);
  const insertAmenity = db.prepare(`INSERT INTO property_amenities (property_id, category, name, details) VALUES (?, ?, ?, ?)`);
  const insertAccessibility = db.prepare(`INSERT INTO property_accessibility (property_id, feature, description) VALUES (?, ?, ?)`);
  const insertRule = db.prepare(`INSERT INTO property_rules (property_id, rule_type, value, details) VALUES (?, ?, ?, ?)`);
  const insertHighlight = db.prepare(`INSERT INTO property_highlights (property_id, highlight) VALUES (?, ?)`);

  const seedAll = db.transaction(() => {
    // Clear existing data
    db.exec('DELETE FROM property_highlights');
    db.exec('DELETE FROM property_rules');
    db.exec('DELETE FROM property_accessibility');
    db.exec('DELETE FROM property_amenities');
    db.exec('DELETE FROM properties');

    for (const p of properties) {
      insertProperty.run(p.id, p.name, p.description, p.property_type, p.city, p.country, p.latitude, p.longitude, p.price_per_night, p.max_guests, p.bedrooms, p.bathrooms, p.rating, p.review_count, p.host_name);

      for (const a of p.amenities) {
        insertAmenity.run(p.id, a.category, a.name, a.details);
      }
      for (const acc of (p.accessibility || [])) {
        insertAccessibility.run(p.id, acc.feature, acc.description);
      }
      for (const r of (p.rules || [])) {
        insertRule.run(p.id, r.rule_type, r.value, r.details);
      }
      for (const h of (p.highlights || [])) {
        insertHighlight.run(p.id, h);
      }
    }
  });

  seedAll();
  console.log(`Seeded ${properties.length} properties with amenities, accessibility features, rules and highlights.`);
}

